function addAnim(scene, key, fps, loop) {
  if (scene.anims.exists(key) || !scene.textures.exists(key)) return;
  scene.anims.create({ key, frames: scene.anims.generateFrameNumbers(key, { start: 0, end: ANIM_META[key].frames - 1 }),
    frameRate: fps, repeat: loop ? -1 : 0 });
}
function createAnims(scene) {
  for (const cls in ANIM_CFG) for (const g of ['', '_f']) for (const a of ANIM_NAMES) {
    const c = ANIM_CFG[cls][a]; if (!c) continue;
    addAnim(scene, `${cls}${g}_${a}`, c.fps, c.loop); addAnim(scene, `${cls}${g}_p_${a}`, c.fps, c.loop);
  }
  for (const t in MON_CFG) {
    const c = MON_CFG[t];
    addAnim(scene, `${t}_walk`, c.walk, true); addAnim(scene, `${t}_attack`, c.attack.fps, false); addAnim(scene, `${t}_death`, c.death, false);
    addAnim(scene, `${t}_hurt`, c.hurt || 24, false);
  }
  addAnim(scene, 'fireball', 16, true);
}
